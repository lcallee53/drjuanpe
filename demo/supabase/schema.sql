-- Esquema del demo Dr. Juanpe (datos de prueba, ningún paciente es real).
-- Las fechas de citas, sesiones, exámenes, pagos y recordatorios van como "dia" relativo a hoy
-- (0 = hoy, -1 = ayer) para que el demo siempre se vea actual.
create table if not exists pacientes (
  id bigint generated by default as identity primary key,
  nombre text not null, edad int, telefono text, programa text, mes int default 1,
  estado text default 'activo', color text, motivo text, tener_presente text,
  puntajes jsonb default '{}'::jsonb, plan jsonb default '[]'::jsonb, pendientes jsonb default '[]'::jsonb,
  creado timestamptz default now()
);
create table if not exists citas (
  id bigint generated by default as identity primary key,
  paciente_id bigint references pacientes(id) on delete cascade,
  dia int not null, hora text not null, tipo text, estado text, movida boolean default false
);
create table if not exists sesiones (
  id bigint generated by default as identity primary key,
  paciente_id bigint references pacientes(id) on delete cascade,
  dia int, titulo text, resumen text, tareas jsonb default '[]'::jsonb
);
create table if not exists examenes (
  id bigint generated by default as identity primary key,
  paciente_id bigint references pacientes(id) on delete cascade,
  marcador text, unidad text, min numeric, max numeric, dia int, valor numeric
);
create table if not exists mensajes (
  id bigint generated by default as identity primary key,
  paciente_id bigint references pacientes(id) on delete cascade,
  canal text, color text check (color in ('verde','amarillo','rojo')), estado text default 'pendiente',
  texto text, respuesta text, creado timestamptz default now()
);
create table if not exists whatsapp (
  id bigint generated by default as identity primary key,
  paciente_id bigint references pacientes(id) on delete cascade,
  de text check (de in ('paciente','letty','juanpe')), texto text, color text, creado timestamptz default now()
);
create table if not exists recordatorios (
  id bigint generated by default as identity primary key,
  paciente_id bigint references pacientes(id) on delete cascade,
  tipo text, texto text, dia int, hora text, estado text default 'programado'
);
create table if not exists leads (
  id bigint generated by default as identity primary key,
  nombre text, fuente text, etapa text, valor numeric, nota text, creado timestamptz default now()
);
create table if not exists pagos (
  id bigint generated by default as identity primary key,
  paciente_id bigint references pacientes(id) on delete cascade,
  concepto text, monto numeric, estado text, dia int, intentos int default 0
);
create table if not exists landings (
  id bigint generated by default as identity primary key,
  titulo text, subtitulo text, cta text, slug text, creado timestamptz default now()
);

-- Seguridad: RLS encendido en todas las tablas. Para el demo (datos ficticios) la llave pública
-- puede leer, crear y editar, pero no borrar. En la versión real esto se cambia por login de Juanpe y Carly.
do $$
declare t text;
begin
  foreach t in array array['pacientes','citas','sesiones','examenes','mensajes','whatsapp','recordatorios','leads','pagos','landings'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists demo_leer on %I', t);
    execute format('drop policy if exists demo_crear on %I', t);
    execute format('drop policy if exists demo_editar on %I', t);
    execute format('create policy demo_leer on %I for select to anon using (true)', t);
    execute format('create policy demo_crear on %I for insert to anon with check (true)', t);
    execute format('create policy demo_editar on %I for update to anon using (true) with check (true)', t);
  end loop;
end $$;

create table if not exists checkins (
  id bigint generated by default as identity primary key,
  paciente_id bigint references pacientes(id) on delete cascade,
  mes text, estado text, resumen text, color text
);
alter table checkins enable row level security;
drop policy if exists demo_leer on checkins; drop policy if exists demo_crear on checkins; drop policy if exists demo_editar on checkins;
create policy demo_leer on checkins for select to anon using (true);
create policy demo_crear on checkins for insert to anon with check (true);
create policy demo_editar on checkins for update to anon using (true) with check (true);
